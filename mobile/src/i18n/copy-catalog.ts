const toEnglish = new Map(COPY_PAIRS);
const toTurkish = new Map<string, string>();
COPY_PAIRS.forEach(([turkish, english]) => {
  if (!toTurkish.has(english)) toTurkish.set(english, turkish);
});

export function localizeCopy(value: string, language: AppLanguage) {
  const exact = language === 'en' ? toEnglish.get(value) : toTurkish.get(value);
  if (exact) return exact;
  if (language === 'tr') return value;

  const replacements: readonly [RegExp, string][] = [
    [/^(\d+) üye$/, '$1 members'],
    [/^(\d+) sürücü$/, '$1 drivers'],
    [/^(\d+) katılımcı$/, '$1 participants'],
    [/^(\d+) değerlendirme$/, '$1 reviews'],
    [/^(\d+) fotoğraf$/, '$1 photos'],
    [/^(\d+) rota noktası seçildi$/, '$1 route points selected'],
    [/^Katılım için en az (\d+)\/100 güven puanı gerekir\.$/, 'A trust score of at least $1/100 is required to participate.'],
    [/^(.+) konvoydan çıkarılsın mı\?$/, 'Remove $1 from the convoy?'],
    [/^(.+) klandan çıkarılsın mı\?$/, 'Remove $1 from the clan?'],
    [/^(.+) klanın yeni kurucusu olsun mu\?$/, 'Make $1 the new clan owner?'],
    [/^(.+) arkadaş listenizden çıkarılsın mı\?$/, 'Remove $1 from your friends?'],
    [/^(.+) için oyun kaydedilsin mi\?$/, 'Save your rating for $1?'],
    [/^(.+) (yardımcı|katılımcı) yapılsın mı\?$/, 'Set $1 as $2?'],
    [/^(.+) ile artık arkadaşsınız\.$/, 'You are now friends with $1.'],
    [/^(.+) konvoyuna katıldınız\.$/, 'You joined the $1 convoy.'],
    [/^(.+) katıldınız\.$/, 'You joined $1.'],
    [/^(.+) kalıcı olarak silinsin mi\?$/, 'Permanently delete $1?'],
    [/^(.+) olarak değiştirildi\.$/, 'Changed to $1.'],
  ];
  for (const [pattern, replacement] of replacements) {
    if (pattern.test(value)) return value.replace(pattern, replacement)
      .replace('yardımcı', 'manager')
      .replace('katılımcı', 'participant');
  }
  return value;
}
